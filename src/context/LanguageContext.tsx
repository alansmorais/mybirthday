export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('party_language');
      if (saved === 'PL' || saved === 'EN') return saved;
    } catch {}
    return 'PL'; // Default to PL so we can show it first or trigger modal
  });

  const [showModal, setShowModal] = useState<boolean>(() => {
    try {
      const saved = localStorage.getItem('party_language');
      return !saved; // Only show modal if language was never chosen
    } catch {
      return true;
    }
  });

  const setLang = (newLang: Language) => {
    setLangState(newLang);
    try {
      localStorage.setItem('party_language', newLang);
    } catch {}
  };

  const t = (key: string, section: string = 'common'): any => {
    const sectionDict = TRANSLATIONS[lang]?.[section];
    if (sectionDict && sectionDict[key] !== undefined) {
      return sectionDict[key];
    }
    // Fallback to English
    return TRANSLATIONS['EN']?.[section]?.[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, showModal, setShowModal, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
